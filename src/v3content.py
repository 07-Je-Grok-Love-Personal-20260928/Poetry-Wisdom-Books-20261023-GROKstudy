def bars(title, items, unit='', note=''):
    """动画条形图（HTML + transform，GPU 合成）。items: (标签, 数值, 颜色, 说明)"""
    mx = max(v for _, v, _, _ in items)
    rows = ''.join(f'<div class="bar" style="--c:{c};--v:{v / mx:.3f}"><span class="bl">{l}</span><span class="bt"><i></i></span><b>{v}{unit}</b><small>{x}</small></div>' for l, v, c, x in items)
    return f'<figure class="bars reveal"><figcaption>📊 {title}</figcaption>{rows}{"<p class=bnote>" + note + "</p>" if note else ""}</figure>'

